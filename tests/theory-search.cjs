const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {normalize, rank} = require('../theories/theory-search.js');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'theories/index.html'), 'utf8');
const cards = [...html.matchAll(/<article class="essay-card"([^>]+)>[\s\S]*?<h2><a href="\.\/([^/]+)\/">([^<]+)<\/a>/g)].map(m => {
  const attr = key => m[1].match(new RegExp(`data-${key}="([^"]*)"`))[1];
  return {id:m[2], topic:`${m[3]} ${attr('topic-keywords')}`, references:attr('reference-keywords'), chapter:Number(attr('chapter'))};
});
assert.equal(cards.length, 15);
const at = (id, q) => { const c=cards.find(c=>c.id===id); return rank(q,c.topic,c.references); };
assert.equal(at('Q010','パリストン'),0);
assert.equal(at('Q010','ビヨンド'),0);
assert.equal(at('Q009','TSK17'),0);
assert.equal(at('Q009','ＴＳＫ－１７'),0);
assert.equal(normalize('tsk-17'),normalize('TSK17'));
assert.equal(at('Q001','ウッディー'),0);
assert.equal(at('emperor-time','ウッディー'),Infinity);
assert.equal(at('Q010','ウッディー'),Infinity);
assert.equal(at('Q002','クラピカ'),1);
assert.equal(rank('パリストン 脱出',cards.find(c=>c.id==='Q010').topic,''),0);
assert.equal(rank('存在しない語','',''),Infinity);
assert.ok(html.includes('id="essay-read-through"'));
assert.ok(cards.filter(c=>c.chapter<=370).every(c=>c.chapter<=370));
const q002=fs.readFileSync(path.join(root,'theories/Q002/index.html'),'utf8');
assert.ok(q002.includes('条件からどこまで絞れるか'));
assert.ok(q002.includes('除外できる解釈'));
assert.ok(q002.includes('event=E370-003'));
assert.ok(q002.includes('event=E376-002'));
console.log('PASS: 15 topic/reference indexes; aliases, primary/secondary ranking, Q010 topics and Q002 conditions');
